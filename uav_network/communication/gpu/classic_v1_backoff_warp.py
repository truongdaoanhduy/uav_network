"""Warp FP32/INT32 vectorized contention window and DIFS/backoff arithmetic.

Derived from classic UavNetSim-v1's native mac/csma_ca.py::CsmaCa.mac_send:
CW = (CW_MIN+1)*2**(transmission_attempt-1)-1,
random.randint(0,CW-1)*SLOT_DURATION, waiting_time=DIFS+backoff.
Inputs include the chosen random backoff integer. The kernel does not
advance any random generator or model CCA waiting/backoff freeze.
"""

from __future__ import annotations
import numpy as np
import warp as wp


@wp.kernel
def _classic_v1_backoff(
    attempt: wp.array(dtype=wp.int32,ndim=2),
    drawn_slot: wp.array(dtype=wp.int32,ndim=2),
    cw_out: wp.array(dtype=wp.int32,ndim=2),
    backoff_out: wp.array(dtype=wp.int32,ndim=2),
    wait_out: wp.array(dtype=wp.int32,ndim=2),
    cw_min: int,
    slot_duration_us: int,
    difs_duration_us: int,
):
    e,u=wp.tid()
    multiplier=wp.int32(1)
    for _ in range(attempt[e,u]-1):
        multiplier=multiplier*2
    cw=(cw_min+1)*multiplier-1
    slots=drawn_slot[e,u]
    backoff=slots*slot_duration_us
    cw_out[e,u]=cw
    backoff_out[e,u]=backoff
    wait_out[e,u]=difs_duration_us+backoff


def compute_backoff_windows(
    transmission_attempt,
    backoff_draw_slots,
    *,
    cw_min: int=31,
    slot_duration_us: int=20,
    difs_duration_us: int=50,
    max_attempts: int=5,
    device: str="cpu",
):
    """Real Warp kernel for E independent worlds x N station attempts.

    The draw is supplied externally, not generated by Warp. Exact source
    matching of the draw distribution requires Python random.Random state
    comparison as a separate experiment, and a time-ordered MAC event
    scheduler is still missing.
    """
    a=np.asarray(transmission_attempt)
    b=np.asarray(backoff_draw_slots)
    if a.ndim!=2 or a.shape!=b.shape or a.size==0:
        raise ValueError("attempt and backoff_draw_slots must be nonempty [E,N]")
    if not np.issubdtype(a.dtype,np.integer) or not np.issubdtype(b.dtype,np.integer):
        raise ValueError("attempt and backoff draws must be integers")
    if int(cw_min)<0 or int(slot_duration_us)<=0 or int(difs_duration_us)<0:
        raise ValueError("Invalid source MAC timing constants")
    if int(max_attempts)<1 or int(max_attempts)>10:
        raise ValueError("Invalid max_attempts")
    if np.any(a<1) or np.any(a>max_attempts):
        raise ValueError("transmission_attempt must be in [1,max_attempts]")
    cw64=(int(cw_min)+1)*(1 << (a.astype(np.int64)-1))-1
    if np.any(cw64>2147483647) or np.any(cw64<1):
        raise ValueError("CW outside supported 32-bit range")
    if np.any(b<0) or np.any(b>=cw64):
        raise ValueError("backoff draw outside native randint(0, CW-1)")
    if np.any((cw64-1)*int(slot_duration_us)+int(difs_duration_us)>2147483647):
        raise ValueError("Backoff time overflow")
    wp.init()
    shape=a.shape
    attempt_w=wp.array(a.astype(np.int32),dtype=wp.int32,device=device)
    slot_w=wp.array(b.astype(np.int32),dtype=wp.int32,device=device)
    cw_w=wp.zeros(shape,dtype=wp.int32,device=device)
    backoff_w=wp.zeros(shape,dtype=wp.int32,device=device)
    wait_w=wp.zeros(shape,dtype=wp.int32,device=device)
    wp.launch(
        _classic_v1_backoff,dim=shape,
        inputs=[attempt_w,slot_w,cw_w,backoff_w,wait_w,
                int(cw_min),int(slot_duration_us),int(difs_duration_us)],
        device=device,
    )
    return {
        "contention_window":cw_w.numpy(),
        "backoff_us":backoff_w.numpy(),
        "wait_difs_plus_backoff_us":wait_w.numpy(),
    }
