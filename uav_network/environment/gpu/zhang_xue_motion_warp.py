"""Batched Warp 1km UAV 2D motion, matching Zhang-Xue CPU map geometry.

CPU or GPU Warp kernel. One Warp thread per env resolves 6 UAV actions
in fixed ID order to match the CPU collision and segment no-fly checks;
this is an environment kernel, not a trainer or network simulator.
"""
from __future__ import annotations

import numpy as np
import warp as wp

@wp.func
def _segment_dist(
    ax:wp.float32,ay:wp.float32,
    bx:wp.float32,by:wp.float32,
    cx:wp.float32,cy:wp.float32
)->wp.float32:
    vx=bx-ax
    vy=by-ay
    denom=vx*vx+vy*vy
    if denom<=wp.float32(1.e-12):
        return wp.sqrt((ax-cx)*(ax-cx)+(ay-cy)*(ay-cy))
    t=((cx-ax)*vx+(cy-ay)*vy)/denom
    t=wp.max(wp.float32(0.),wp.min(wp.float32(1.),t))
    dx=ax+t*vx-cx
    dy=ay+t*vy-cy
    return wp.sqrt(dx*dx+dy*dy)

@wp.kernel
def _move_six(
    old: wp.array(dtype=wp.vec2f,ndim=2),
    forbidden: wp.array(dtype=wp.vec3f,ndim=2),
    actions: wp.array(dtype=wp.vec2f,ndim=2),
    new_positions: wp.array(dtype=wp.vec2f,ndim=2),
    velocity: wp.array(dtype=wp.vec2f,ndim=2),
    safety: wp.array(dtype=wp.int32,ndim=1),
    boundary: wp.array(dtype=wp.int32,ndim=1),
    n_zones:wp.int32,
    dt:wp.float32,
    speed:wp.float32,
    separation:wp.float32,
    step_index:wp.int32,
):
    e=wp.tid()
    for u in range(6):
        new_positions[e,u]=old[e,u]
    count_s=wp.int32(0)
    count_b=wp.int32(0)
    # Mirror CPU's alternating priority without per-world host intervention.
    for order in range(6):
        u = order
        if step_index % 2 != 0:
            u = 5 - order
        ax=old[e,u][0]
        ay=old[e,u][1]
        dx=actions[e,u][0]
        dy=actions[e,u][1]
        norm=wp.sqrt(dx*dx+dy*dy)
        if norm>wp.float32(1.):
            dx=dx/norm
            dy=dy/norm
        nx=ax+dx*speed*dt
        ny=ay+dy*speed*dt
        blocked=wp.int32(0)
        if nx<wp.float32(0.) or ny<wp.float32(0.) or nx>=wp.float32(1000.) or ny>=wp.float32(1000.):
            count_b+=1
            blocked=1
        if blocked==0:
            for j in range(n_zones):
                z=forbidden[e,j]
                if _segment_dist(ax,ay,nx,ny,z[0],z[1])<z[2]:
                    count_s+=1
                    blocked=1
                    break
        if blocked==0:
            for other in range(6):
                if other==u:
                    continue
                op=old[e,other]
                np=new_positions[e,other]
                oldgap=_segment_dist(ax,ay,nx,ny,op[0],op[1])
                xx=nx-np[0]
                yy=ny-np[1]
                newgap=wp.sqrt(xx*xx+yy*yy)
                if oldgap<separation or newgap<separation:
                    count_s+=1
                    blocked=1
                    break
        if blocked==0:
            new_positions[e,u]=wp.vec2f(nx,ny)
        res=new_positions[e,u]
        velocity[e,u]=wp.vec2f((res[0]-ax)/dt,(res[1]-ay)/dt)
    safety[e]=count_s
    boundary[e]=count_b


def warp_move_batch(
    positions_xy,no_fly_zones,actions_xy,
    *,
    dt=1.,max_speed=50.,safe_distance=50.,step_index=0,device="cpu",
):
    """Vectorized E×6 motion with CPU-equivalent sequential collision resolution.

    The input scene already contains no-fly regions generated by the shared
    map geometry sampler. Communication blackouts do not block movement.
    """
    pos=np.asarray(positions_xy,dtype=np.float32)
    zones=np.asarray(no_fly_zones,dtype=np.float32)
    acts=np.asarray(actions_xy,dtype=np.float32)
    if pos.ndim!=3 or pos.shape[1:]!=(6,2):
        raise ValueError("positions_xy must be [E,6,2]")
    e=pos.shape[0]
    if e<1 or zones.ndim!=3 or zones.shape[0]!=e or zones.shape[2]!=3:
        raise ValueError("no_fly_zones must be [E,num_zones,3]")
    if acts.shape!=pos.shape:
        raise ValueError("actions_xy must be [E,6,2]")
    if not np.isfinite(pos).all() or not np.isfinite(zones).all() or not np.isfinite(acts).all():
        raise ValueError("All positions/zones/actions must be finite")
    if not (float(dt)>0. and float(max_speed)>0. and float(safe_distance)>0.):
        raise ValueError("dt, max_speed, separation must be positive")
    wp.init()
    pos_w=wp.array(pos,dtype=wp.vec2f,device=device)
    zones_w=wp.array(zones,dtype=wp.vec3f,device=device)
    action_w=wp.array(acts,dtype=wp.vec2f,device=device)
    new_w=wp.zeros((e,6),dtype=wp.vec2f,device=device)
    vel_w=wp.zeros((e,6),dtype=wp.vec2f,device=device)
    safety_w=wp.zeros(e,dtype=wp.int32,device=device)
    boundary_w=wp.zeros(e,dtype=wp.int32,device=device)
    wp.launch(
        _move_six,dim=e,
        inputs=[pos_w,zones_w,action_w,new_w,vel_w,
                safety_w,boundary_w,zones.shape[1],dt,max_speed,safe_distance,int(step_index)],
        device=device,
    )
    return new_w.numpy(),vel_w.numpy(),safety_w.numpy(),boundary_w.numpy()
